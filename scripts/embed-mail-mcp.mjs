// Writes plugins/mail/src/core/mcp-server-source.ts from plugins/mail/mcp/makosh-mail-mcp.mjs,
// so the settings page can save the server file without reading the disk.
// Run from the repository root after changing the .mjs file; a test compares the two.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../plugins/mail/", import.meta.url));
const source = readFileSync(`${root}mcp/makosh-mail-mcp.mjs`, "utf8");
writeFileSync(
  `${root}src/core/mcp-server-source.ts`,
  `// Generated by scripts/embed-mail-mcp.mjs from mcp/makosh-mail-mcp.mjs. Do not edit: change that file and run the script.\n` +
    `// The local MCP server for assistants outside BB, as text the settings page saves to a file.\n` +
    `export const MCP_SERVER_FILE_NAME = "makosh-mail-mcp.mjs";\n` +
    `export const MCP_SERVER_SOURCE: string = ${JSON.stringify(source)};\n`,
);
