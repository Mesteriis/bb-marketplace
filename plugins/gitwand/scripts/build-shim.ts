// Regenerates src/adapters/bb/shim-source.generated.ts from src/shim/tauri-shim.ts.
//   node scripts/build-shim.ts   (also: npm run shim)
import { readFileSync, writeFileSync } from "node:fs";
import { transpileShim } from "./lib/shim-build.ts";

const root = new URL("../", import.meta.url);
const js = transpileShim(readFileSync(new URL("src/shim/tauri-shim.ts", root), "utf8"));
writeFileSync(
  new URL("src/adapters/bb/shim-source.generated.ts", root),
  `// @generated by scripts/build-shim.ts from src/shim/tauri-shim.ts — do not edit.\nexport const SHIM_SOURCE = ${JSON.stringify(js)};\n`,
);
console.log(`shim: ${js.length} characters`);
