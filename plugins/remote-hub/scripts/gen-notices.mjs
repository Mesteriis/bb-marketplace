// Regenerates the "Every linked crate" table in THIRD_PARTY_NOTICES.md from `cargo metadata` (normal dependencies of the
// release helper for aarch64-apple-darwin). The hand-written sections above it are not touched.
//   node scripts/gen-notices.mjs        rewrite the table
//   node scripts/gen-notices.mjs --check   fail when the file is not up to date
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const file = join(root, "THIRD_PARTY_NOTICES.md");
const manifest = join(root, "helper", "Cargo.toml");
const BEGIN = "<!-- BEGIN GENERATED CRATES -->";
const END = "<!-- END GENERATED CRATES -->";

const meta = JSON.parse(execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--filter-platform", "aarch64-apple-darwin", "--manifest-path", manifest], { encoding: "utf8", maxBuffer: 256 * 1024 * 1024 }));
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const node = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
// Walk only normal (non-dev, non-build) edges from the helper.
const seen = new Set();
const stack = [meta.resolve.root];
while (stack.length > 0) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const dep of node.get(id).deps) if (dep.dep_kinds.some((k) => k.kind === null)) stack.push(dep.pkg);
}
const rows = [...seen]
  .map((id) => byId.get(id))
  .filter((p) => p.name !== "remote-hub-helper")
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
  .map((p) => `| ${p.name} | ${p.version} | ${p.license ?? "see source"} |`);
const block = `${BEGIN}\n\n## Every linked crate\n\nGenerated by \`scripts/gen-notices.mjs\` from Cargo.lock: the ${rows.length} crates linked into the release helper (normal dependencies, aarch64-apple-darwin). Licence texts are in each crate's source distribution (crates.io).\n\n| Crate | Version | Licence |\n| --- | --- | --- |\n${rows.join("\n")}\n\n${END}`;

const current = readFileSync(file, "utf8");
const start = current.indexOf(BEGIN);
const stop = current.indexOf(END);
const next = start >= 0 && stop > start ? current.slice(0, start) + block + current.slice(stop + END.length) : current.trimEnd() + "\n\n" + block + "\n";
if (process.argv.includes("--check")) {
  if (next !== current) {
    console.error("THIRD_PARTY_NOTICES.md is out of date: run node scripts/gen-notices.mjs");
    process.exit(1);
  }
  console.log("generated crate table is current");
} else {
  writeFileSync(file, next);
  console.log(`wrote ${rows.length} crates`);
}
