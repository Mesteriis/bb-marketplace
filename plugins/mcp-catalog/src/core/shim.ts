export const LEGACY_STDIO_SHIM = [
  "\"\"\"Answer the MCP 2026 `server/discover` probe for a legacy stdio server.",
  "",
  "The BB bridge opens every stdio server with a `server/discover` request and",
  "falls back to the classic `initialize` handshake when the server returns",
  "\"method not found\". Some older servers never answer an unknown method sent",
  "before `initialize`, so the bridge waits until its deadline. This shim",
  "answers that one probe itself and passes everything else through unchanged.",
  "",
  "Usage: python3 legacy-stdio-shim.py <command> [args...]",
  "\"\"\"",
  "import json",
  "import subprocess",
  "import sys",
  "import threading",
  "",
  "PROBE = \"server/discover\"",
  "",
  "",
  "def main() -> int:",
  "    child = subprocess.Popen(sys.argv[1:], stdin=subprocess.PIPE, stdout=subprocess.PIPE, bufsize=0)",
  "    out_lock = threading.Lock()",
  "",
  "    def write_out(data: bytes) -> None:",
  "        with out_lock:",
  "            sys.stdout.buffer.write(data)",
  "            sys.stdout.buffer.flush()",
  "",
  "    def pump_child_output() -> None:",
  "        for line in child.stdout:",
  "            write_out(line)",
  "",
  "    reader = threading.Thread(target=pump_child_output, daemon=True)",
  "    reader.start()",
  "    try:",
  "        for line in sys.stdin.buffer:",
  "            try:",
  "                message = json.loads(line)",
  "            except ValueError:",
  "                message = None",
  "            if isinstance(message, dict) and message.get(\"method\") == PROBE and \"id\" in message:",
  "                reply = {\"jsonrpc\": \"2.0\", \"id\": message[\"id\"],",
  "                         \"error\": {\"code\": -32601, \"message\": \"Method not found\"}}",
  "                write_out((json.dumps(reply) + \"\\n\").encode())",
  "                continue",
  "            child.stdin.write(line)",
  "            child.stdin.flush()",
  "    except BrokenPipeError:",
  "        pass",
  "    finally:",
  "        try:",
  "            child.stdin.close()",
  "        except BrokenPipeError:",
  "            pass",
  "        child.wait()",
  "        reader.join(timeout=2)",
  "    return child.returncode or 0",
  "",
  "",
  "if __name__ == \"__main__\":",
  "    raise SystemExit(main())",
  "",
].join("\n");
