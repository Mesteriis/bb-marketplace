#!/usr/bin/env node
// Bundles the Account Pooler model bridge (src/adapters/bb/pool-bridge.ts and
// its contract) into one self-contained script and stores it as a string module.
// Makosh AI inserts that script into Account Pooler when the bridge is missing.
// Git installs build without devDependencies, so the generated module is committed;
// tests/pool-bridge-bundle.test.ts fails when it is stale. Run: npm run build:bridge
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUT = resolve(root, "src/adapters/bb/pool-bridge.bundle.generated.ts");

export async function bundlePoolBridge() {
  const result = await build({
    entryPoints: [resolve(root, "src/adapters/bb/pool-bridge.ts")],
    bundle: true,
    platform: "node",
    target: "node22",
    format: "iife",
    globalName: "__makoshPoolBridge",
    minify: true,
    legalComments: "none",
    write: false,
    logLevel: "silent",
  });
  // The bundle lands inside an ES module, which is strict already.
  return result.outputFiles[0].text.trim().replace(/^"use strict";/, "");
}

export function generatedModule(bundle) {
  return [
    "// Generated by scripts/build-pool-bridge.mjs from pool-bridge.ts. Do not edit.",
    "// Bundled third-party code: zod (MIT) and @get-bb/plugin-sdk.",
    `export const POOL_BRIDGE_BUNDLE: string = ${JSON.stringify(bundle)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generatedModule(await bundlePoolBridge()));
  console.log(`wrote ${OUTPUT}`);
}
